# frozen_string_literal: true

require 'json'
require 'fileutils'

module Abqari
  # D3-based data visualizations of your site's content. Off by default —
  # toggle in config/site.yml under `visualizations:`. When enabled, abqari
  # generates per-viz JSON data files and HTML pages at build time. The
  # viz pages load D3 (vendored at /assets/d3/d3.v7.min.js) and the
  # corresponding JSON, then render entirely client-side.
  #
  # Three visualizations ship:
  #   - tag-bubble:           circle-pack of tags sized by post count
  #   - tag-cooccurrence:     chord diagram of tags that appear together
  #   - topic-constellation:  force graph of posts connected by shared tags
  #
  # Each is independently config-toggleable. When all are off, no JSON is
  # written, no pages are generated, D3 isn't pulled into the asset pipeline.
  class Visualizations
    VIZ_NAMES = %w[tag-bubble tag-cooccurrence topic-constellation].freeze

    def initialize(site)
      @site = site
    end

    def enabled?
      enabled_visualizations.any?
    end

    def enabled_visualizations
      config = @site.config['visualizations'] || {}
      VIZ_NAMES.select { |name| config[name.tr('-', '_')] == true }
    end

    # Generated VizPage instances — appended to Site's @generated_pages so
    # they go through the normal render pipeline (post-process, minification,
    # incremental check, etc.).
    def pages
      enabled_visualizations.map { |name| VizPage.new(name, @site) }
    end

    # Writes the JSON data files. Called from Site#build after pages render.
    def write_data
      return unless enabled?

      enabled_visualizations.each { |name| write_one(name) }
    end

    private

    def write_one(name)
      data = case name
             when 'tag-bubble'           then tag_bubble_data
             when 'tag-cooccurrence'     then tag_cooccurrence_data
             when 'topic-constellation'  then topic_constellation_data
             end

      dest = File.join(@site.output_dir, 'visualizations', "#{name}.json")
      FileUtils.mkdir_p(File.dirname(dest))
      File.write(dest, JSON.pretty_generate(data))
    end

    # Tag bubble — array of { name, note_count } (note_count for parity with
    # Cogent's chart code; conceptually it's "post_count" here).
    def tag_bubble_data
      tags = @site.posts_by_term('tags').map do |tag, posts|
        { 'name' => tag, 'note_count' => posts.size }
      end.sort_by { |t| -t['note_count'] }

      { 'tags' => tags }
    end

    # Tag co-occurrence — square matrix where matrix[i][j] is the number of
    # posts that have both tags[i] and tags[j].
    def tag_cooccurrence_data
      grouped = @site.posts_by_term('tags')
      tags = grouped.keys.sort

      matrix = tags.map do |tag_a|
        tags.map do |tag_b|
          next 0 if tag_a == tag_b

          grouped[tag_a].count { |post| grouped[tag_b].include?(post) }
        end
      end

      { 'tags' => tags, 'matrix' => matrix }
    end

    # Topic constellation — nodes are posts, links connect posts that share
    # at least one tag. Link weight = number of shared tags.
    def topic_constellation_data
      posts = @site.posts
      nodes = posts.map do |post|
        {
          'id' => post.url,
          'title' => post.title,
          'tags' => post.tags,
          'date' => post.date&.iso8601
        }.compact
      end

      links = []
      posts.each_with_index do |a, i|
        posts[(i + 1)..].each do |b|
          shared = a.tags & b.tags
          next if shared.empty?

          links << { 'source' => a.url, 'target' => b.url, 'weight' => shared.size }
        end
      end

      { 'nodes' => nodes, 'links' => links }
    end
  end

  # A single visualization page. Generated by Visualizations#pages and added
  # to Site's @generated_pages, so it renders through the normal pipeline.
  class VizPage
    TITLES = {
      'tag-bubble' => 'Tag Bubble',
      'tag-cooccurrence' => 'Tag Co-occurrence',
      'topic-constellation' => 'Topic Constellation'
    }.freeze

    DESCRIPTIONS = {
      'tag-bubble' => 'Each tag rendered as a circle, sized by the number of posts using it.',
      'tag-cooccurrence' => 'Which tags appear together — chord diagram of tag overlap across posts.',
      'topic-constellation' => 'Posts as nodes, connected by shared tags. Drag to explore.'
    }.freeze

    attr_reader :viz_name, :site

    def initialize(viz_name, site)
      @viz_name = viz_name
      @site = site
    end

    def title
      TITLES[viz_name]
    end

    def description
      DESCRIPTIONS[viz_name]
    end

    def content
      ''
    end

    def frontmatter
      {}
    end

    def url
      "/visualizations/#{viz_name}/"
    end

    def output_path
      File.join(@site.output_dir, 'visualizations', viz_name, 'index.html')
    end

    def write
      FileUtils.mkdir_p(File.dirname(output_path))
      File.write(output_path, @site.post_process(render, page: self))
    end

    # Used by Site's incremental render: re-render when shared deps change
    # or any post changes (since post data feeds the JSON).
    def needs_render?
      return true unless File.exist?(output_path)

      output_mtime = File.mtime(output_path)
      return true if @site.shared_deps_mtime > output_mtime

      @site.posts.any? { |post| (post.lastmod || Time.now) > output_mtime }
    end

    def lastmod
      @site.posts.map(&:lastmod).compact.max
    end

    def bundle_images
      []
    end

    private

    def render
      RenderContext.new(self, @site).render_layout('visualization')
    end
  end
end
